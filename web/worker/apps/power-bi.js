/**
 * Power BI / Excel Power Query feed builder.
 *
 * There is no third-party API here. The page generates Power Query M scripts that call the ReAI
 * public API (https://app.reai.no/openapi/public) directly from Power BI Desktop, the Power BI
 * service or Excel with a ReAI user API key (`Authorization: Bearer <key>` plus `X-Tenant-Id`).
 * The key is never sent to apps.reai.no: the scripts reference a Power Query parameter named
 * `ReAIToken` that the user creates inside Power BI or Excel.
 *
 * ReAI endpoints used by the generated scripts:
 * - GET /api/me (MeRes.tenants: id, companyName, currencyCode)
 * - GET /api/ledger/general?startDate&endDate[&accountFrom&accountTo] (GeneralLedgerRes)
 * - GET /api/invoices?startDate&endDate&page&pageSize (ApiPageRes_InvoiceOverviewRes)
 */

/** @typedef {'postings' | 'pnl' | 'balance' | 'invoices' | 'companies'} FeedKind */
/** @typedef {{ tenantId: number, startDate: string, endDate: string, baseUrl?: string }} FeedOptions */

const BRAND = 'Power BI';
const TITLE = 'Power BI & Excel Feed';
const LEAD = 'Generate ready-to-paste Power Query scripts that load ReAI ledger postings, profit and loss, balances and invoices into Power BI or Excel with your own ReAI user API key.';
const TOKEN_URL = 'https://app.reai.no/user/profile#user-access-tokens';
const DATE_RE = /^[0-9]{4}-[0-9]{2}-[0-9]{2}$/;

/** @type {Record<FeedKind, { label: string, queryName: string, description: string }>} */
export const FEEDS = {
  postings: { label: 'General ledger postings', queryName: 'ReAI_Postings', description: 'One row per posting line with account, voucher, VAT code, amount, project, customer, supplier and employee.' },
  pnl: { label: 'Profit and loss by account', queryName: 'ReAI_ProfitAndLoss', description: 'Period movement per result account 3000 to 8999, grouped by NS 4102 account class.' },
  balance: { label: 'Balance sheet by account', queryName: 'ReAI_Balances', description: 'Closing balance per balance account 1000 to 2999 on the end date.' },
  invoices: { label: 'Customer invoices', queryName: 'ReAI_Invoices', description: 'Invoices and credit notes issued in the period with totals, VAT, paid and outstanding amounts.' },
  companies: { label: 'Companies (tenant IDs)', queryName: 'ReAI_Companies', description: 'Companies your key can access, with the tenant ID each feed needs.' },
};

/** @type {FeedKind[]} */
const FEED_ORDER = ['postings', 'pnl', 'balance', 'invoices', 'companies'];

/** @param {unknown} raw @returns {raw is FeedKind} */
function isFeed(raw) {
  return typeof raw === 'string' && Object.hasOwn(FEEDS, raw);
}

/** @param {string} value Escapes a value for a Power Query M text literal. */
function mText(value) {
  return `"${value.replace(/"/g, '""')}"`;
}

/** @param {FeedOptions} opts */
function validateOptions(opts) {
  if (!Number.isInteger(opts.tenantId) || opts.tenantId <= 0) throw new HttpError(400, 'Choose a company or enter a positive ReAI tenant ID.');
  if (!DATE_RE.test(opts.startDate) || !DATE_RE.test(opts.endDate)) throw new HttpError(400, 'Dates must use YYYY-MM-DD.');
  if (opts.startDate > opts.endDate) throw new HttpError(400, 'Start date must be on or before end date.');
}

/**
 * Shared M prelude: settings, headers and a JSON helper that keeps the data source URL static
 * (RelativePath + Query) so scheduled refresh works in the Power BI service.
 * @param {FeedKind} kind
 * @param {FeedOptions} opts
 */
function prelude(kind, opts) {
  const withTenant = kind !== 'companies';
  return [
    `// ReAI ${FEEDS[kind].label} for Power BI / Excel Power Query`,
    '// Generated by https://apps.reai.no/app/power-bi/ from the ReAI public API (https://app.reai.no/openapi/public).',
    '// Before use: create a Text parameter named ReAIToken (Manage Parameters > New Parameter) and paste your',
    `// ReAI user API key from ${TOKEN_URL} into it. Never paste the key into this script.`,
    'let',
    `    BaseUrl = ${mText(opts.baseUrl ?? 'https://app.reai.no')},`,
    ...(withTenant ? [`    TenantId = ${mText(String(opts.tenantId))},`, `    StartDate = ${mText(opts.startDate)},`, `    EndDate = ${mText(opts.endDate)},`] : []),
    '    Headers = [',
    '        Authorization = "Bearer " & ReAIToken,',
    ...(withTenant ? ['        #"X-Tenant-Id" = TenantId,'] : []),
    '        Accept = "application/json",',
    '        #"Accept-Language" = "en"',
    '    ],',
    '    GetJson = (path as text, query as record) as any =>',
    '        Json.Document(Web.Contents(BaseUrl, [RelativePath = path, Query = query, Headers = Headers])),',
    '    ToDate = (value as nullable text) as nullable date =>',
    '        if value = null then null else Date.FromText(Text.Start(value, 10), [Format = "yyyy-MM-dd", Culture = "en-US"]),',
  ];
}

/**
 * Builds a self-contained Power Query M script for one ReAI feed.
 * @param {FeedKind} kind
 * @param {FeedOptions} opts
 * @returns {string}
 */
export function buildPowerQuery(kind, opts) {
  validateOptions(opts);
  const head = prelude(kind, opts);
  /** @type {string[]} */
  let body;
  if (kind === 'postings') {
    body = [
      '    Ledger = GetJson("api/ledger/general", [startDate = StartDate, endDate = EndDate]),',
      '    Rows = List.Combine(List.Transform(Ledger[accounts], (a) =>',
      '        List.Transform(a[postings], (p) => [',
      '            postingId = p[postingId],',
      '            date = ToDate(p[date]),',
      '            voucherNumber = p[voucherNumber]?,',
      '            voucherId = p[voucherId]?,',
      '            accountNumber = a[accountNumber],',
      '            accountName = a[accountName],',
      '            description = p[description]?,',
      '            vatCode = p[vatCode]?,',
      '            amount = p[amount],',
      '            currencyCode = p[currencyCode],',
      '            currencyAmount = p[currencyAmount],',
      '            projectName = p[projectName]?,',
      '            customerName = p[customerName]?,',
      '            supplierName = p[supplierName]?,',
      '            employeeName = p[employeeName]?',
      '        ]))),',
      '    Result = Table.FromRecords(Rows, type table [',
      '        postingId = Int64.Type, date = date, voucherNumber = nullable text, voucherId = nullable Int64.Type,',
      '        accountNumber = text, accountName = text, description = nullable text, vatCode = nullable text,',
      '        amount = number, currencyCode = text, currencyAmount = number, projectName = nullable text,',
      '        customerName = nullable text, supplierName = nullable text, employeeName = nullable text',
      '    ])',
    ];
  } else if (kind === 'pnl') {
    body = [
      '    Ledger = GetJson("api/ledger/general", [startDate = StartDate, endDate = EndDate, accountFrom = "3000", accountTo = "8999"]),',
      '    ClassOf = (account as text) as text =>',
      '        let c = Text.Start(account, 1) in',
      '        if c = "3" then "3 Operating income"',
      '        else if c = "4" then "4 Cost of goods sold"',
      '        else if c = "5" then "5 Payroll expenses"',
      '        else if c = "6" or c = "7" then "6-7 Other operating expenses"',
      '        else "8 Financial items and tax",',
      '    Rows = List.Transform(Ledger[accounts], (a) =>',
      '        let movement = List.Sum(List.Transform(a[postings], (p) => p[amount])) ?? 0 in [',
      '            periodStart = ToDate(StartDate),',
      '            periodEnd = ToDate(EndDate),',
      '            accountNumber = a[accountNumber],',
      '            accountName = a[accountName],',
      '            accountClass = ClassOf(a[accountNumber]),',
      '            amount = movement,',
      '            resultAmount = -movement',
      '        ]),',
      '    // amount is debit positive as in the ledger; resultAmount shows income as positive and costs as negative.',
      '    Result = Table.FromRecords(Rows, type table [',
      '        periodStart = date, periodEnd = date, accountNumber = text, accountName = text,',
      '        accountClass = text, amount = number, resultAmount = number',
      '    ])',
    ];
  } else if (kind === 'balance') {
    body = [
      '    Ledger = GetJson("api/ledger/general", [startDate = EndDate, endDate = EndDate, accountFrom = "1000", accountTo = "2999"]),',
      '    Rows = List.Transform(Ledger[accounts], (a) => [',
      '        asOfDate = ToDate(EndDate),',
      '        accountNumber = a[accountNumber],',
      '        accountName = a[accountName],',
      '        side = if Text.Start(a[accountNumber], 1) = "1" then "Assets" else "Equity and liabilities",',
      '        closingBalance = a[closingBalance]',
      '    ]),',
      '    Result = Table.FromRecords(Rows, type table [',
      '        asOfDate = date, accountNumber = text, accountName = text, side = text, closingBalance = number',
      '    ])',
    ];
  } else if (kind === 'invoices') {
    body = [
      '    GetPage = (page as number) => GetJson("api/invoices", [startDate = StartDate, endDate = EndDate, page = Text.From(page), pageSize = "200"]),',
      '    Pages = List.Generate(',
      '        () => [page = 1, res = GetPage(1)],',
      '        each [res] <> null and [page] <= 500,',
      '        each if [res][hasNext] then [page = [page] + 1, res = GetPage([page] + 1)] else [page = [page] + 1, res = null],',
      '        each [res][items]',
      '    ),',
      '    Rows = List.Transform(List.Combine(Pages), (i) => [',
      '        id = i[id]?,',
      '        number = i[number],',
      '        issueDate = ToDate(i[issueDate]),',
      '        dueDate = ToDate(i[dueDate]?),',
      '        customerId = i[customerId]?,',
      '        customerName = i[customerName]?,',
      '        currencyCode = i[currencyCode],',
      '        totalExclVatAmount = i[totalExclVatAmount],',
      '        totalVatAmount = i[totalVatAmount],',
      '        totalAmount = i[totalAmount],',
      '        companyCurrencyAmount = i[invoiceCompanyCurrencyAmount],',
      '        paidAmount = i[paidAmount],',
      '        outstanding = i[outstanding],',
      '        lastPaymentDate = ToDate(i[lastPaymentDate]?),',
      '        projectName = i[projectName]?,',
      '        orderNumber = i[orderNumber]?,',
      '        isCreditNote = i[creditedInvoiceId]? <> null',
      '    ]),',
      '    Result = Table.FromRecords(Rows, type table [',
      '        id = nullable Int64.Type, number = text, issueDate = date, dueDate = nullable date,',
      '        customerId = nullable Int64.Type, customerName = nullable text, currencyCode = text,',
      '        totalExclVatAmount = number, totalVatAmount = number, totalAmount = number,',
      '        companyCurrencyAmount = number, paidAmount = number, outstanding = number,',
      '        lastPaymentDate = nullable date, projectName = nullable text, orderNumber = nullable text,',
      '        isCreditNote = logical',
      '    ])',
    ];
  } else {
    body = [
      '    Me = GetJson("api/me", []),',
      '    Rows = List.Transform(Me[tenants], (t) => [tenantId = t[id], companyName = t[companyName], currencyCode = t[currencyCode]]),',
      '    Result = Table.FromRecords(Rows, type table [tenantId = Int64.Type, companyName = text, currencyCode = text])',
    ];
  }
  return [...head, ...body, 'in', '    Result', ''].join('\n');
}

/** @param {FormData} form @param {number} sessionTenant @returns {{ opts: FeedOptions, kinds: FeedKind[] }} */
function readForm(form, sessionTenant) {
  const picked = Number(form.get('tenantId') ?? '0');
  const manual = Number(String(form.get('manualTenantId') ?? '').trim() || '0');
  const tenantId = manual > 0 ? manual : picked > 0 ? picked : sessionTenant;
  const kinds = form.getAll('feed').map(String).filter(isFeed);
  const opts = { tenantId, startDate: String(form.get('startDate') ?? '').trim(), endDate: String(form.get('endDate') ?? '').trim() };
  validateOptions(opts);
  if (kinds.length === 0) throw new HttpError(400, 'Choose at least one dataset.');
  return { opts, kinds };
}

/** @param {FeedKind[]} kinds @param {FeedOptions} opts @param {boolean} isSample */
function renderScripts(kinds, opts, isSample) {
  return html`
    ${reaiCard({
      eyebrow: 'REAI → POWER QUERY',
      title: `${kinds.length} ${kinds.length === 1 ? 'query' : 'queries'} for tenant ${opts.tenantId}`,
      badge: isSample ? reaiBadge({ text: 'Synthetic sample', tone: 'accent' }) : reaiBadge({ text: `${opts.startDate} to ${opts.endDate}`, tone: 'success' }),
      body: html`<ol class="stack-sm">
          <li>Power BI Desktop: <strong>Home → Transform data → Manage Parameters → New Parameter</strong>. Excel: <strong>Data → Get Data → Launch Power Query Editor → Manage Parameters</strong>. Name it <code>ReAIToken</code>, type Text, and paste your <a href="${TOKEN_URL}" target="_blank" rel="noopener">ReAI user API key</a>.</li>
          <li>For each dataset: <strong>New Source → Blank Query → Advanced Editor</strong>, paste the script and rename the query as shown.</li>
          <li>When asked for credentials, choose <strong>Anonymous</strong>. The key travels in the Authorization header set by the script.</li>
        </ol>
        ${reaiCallout({ tone: 'warn', body: 'The key is saved inside your .pbix or .xlsx file and has the same permissions as your ReAI user. Use a dedicated key and revoke it in ReAI when the report is retired.' })}`,
    })}
    ${kinds.map((kind) => {
      const script = buildPowerQuery(kind, opts);
      return reaiCard({
        eyebrow: FEEDS[kind].queryName,
        title: FEEDS[kind].label,
        compact: true,
        body: html`<p class="muted-note">${FEEDS[kind].description}</p>
          <textarea class="mono" readonly rows="${Math.min(30, script.split('\n').length)}" spellcheck="false" aria-label="${FEEDS[kind].label} Power Query script" style="width:100%;font-size:12px;white-space:pre;overflow:auto">${script}</textarea>
          ${isSample ? '' : html`<form method="post" action="/app/power-bi/download" class="inline-row">
            <input type="hidden" name="feed" value="${kind}"><input type="hidden" name="manualTenantId" value="${opts.tenantId}">
            <input type="hidden" name="startDate" value="${opts.startDate}"><input type="hidden" name="endDate" value="${opts.endDate}">
            <button type="submit" class="button secondary">Download ${FEEDS[kind].queryName}.pq</button>
          </form>`}`,
      });
    })}
  `;
}

/**
 * Handles /app/power-bi/* routes.
 * @param {Request} request
 * @param {import('../lib/types.d.ts').Env} env
 * @returns {Promise<Response>}
 */
export async function handle(request, env) {
  const { pathname } = new URL(request.url);
  const basePath = '/app/power-bi';
  if (pathname === basePath && (request.method === 'GET' || request.method === 'HEAD')) return Response.redirect(new URL(`${basePath}/`, request.url), 301);
  if (pathname === `${basePath}/` && (request.method === 'GET' || request.method === 'HEAD')) {
    const session = await readSession(env, request);
    const today = new Date().toISOString().slice(0, 10);
    const yearStart = `${today.slice(0, 4)}-01-01`;
    const tenants = session?.tenants ?? [];
    const body = html`
      <section class="app-intro"><p class="eyebrow">BI & REPORTING</p><h1>${TITLE}</h1><p class="lead">${LEAD}</p></section>
      <div class="stack">
        ${reaiCard({
          eyebrow: 'STEP 1 · REAI USER API KEY',
          title: 'Create a key for Power BI',
          body: html`<p>Open <a href="${TOKEN_URL}" target="_blank" rel="noopener">ReAI → Profile → User API keys</a> and choose <strong>New user API key</strong>. You paste it into Power BI or Excel only. This page never asks for it, sends it or stores it.</p>`,
        })}
        ${renderConnectPanel(session, { clientId: 'reai-power-bi-web', clientName: `ReAI ${BRAND} Feed (Web)` })}
        ${reaiCard({
          eyebrow: 'STEP 2 · BUILD THE FEED',
          title: 'Choose company, period and datasets',
          body: html`<p class="muted-note">Connecting above is optional and only fills in the company list and a data preview. Without it, enter the tenant ID, or generate the Companies query to look it up.</p>
            <form class="stack" hx-post="${basePath}/generate" hx-target="#pbi-output" hx-swap="innerHTML">
              <div class="mapping-grid">
                ${tenants.length > 0
                  ? html`<div class="field"><label for="pbi-tenant">ReAI company</label><select id="pbi-tenant" name="tenantId">${tenants.map((t) => html`<option value="${t.id}"${t.id === session?.tenantId ? html` selected` : ''}>${t.companyName} (#${t.id})</option>`)}</select></div>`
                  : html`<div class="field"><label for="pbi-manual">ReAI tenant ID</label><input id="pbi-manual" name="manualTenantId" type="number" min="1" step="1" inputmode="numeric" placeholder="e.g. 42"></div>`}
                <div class="field"><label for="pbi-start">Start date</label><input id="pbi-start" name="startDate" type="date" value="${yearStart}" required></div>
                <div class="field"><label for="pbi-end">End date</label><input id="pbi-end" name="endDate" type="date" value="${today}" required></div>
              </div>
              <fieldset class="stack-sm"><legend>Datasets</legend>
                ${FEED_ORDER.map((k) => html`<label class="check-row"><input type="checkbox" name="feed" value="${k}" checked> <strong>${FEEDS[k].label}</strong> · ${FEEDS[k].description}</label>`)}
              </fieldset>
              <div class="inline-row">
                <button type="submit" class="button primary">Generate Power Query scripts</button>
                <button type="button" class="button secondary" hx-post="${basePath}/sample" hx-target="#pbi-output" hx-swap="innerHTML">Load sample scripts</button>
                ${session && session.tenantId > 0 ? html`<button type="button" class="button secondary" hx-post="${basePath}/preview" hx-include="closest form" hx-target="#pbi-output" hx-swap="innerHTML">Preview data</button>` : ''}
              </div>
            </form>`,
        })}
        <div id="pbi-output" class="stack"></div>
      </div>
    `;
    return htmlResponse(appShell({ title: TITLE, description: LEAD, activePath: `${basePath}/`, body }));
  }
  if (request.method !== 'POST') return errorResponse('Method not allowed.', 405);
  const originError = requireSameOrigin(request);
  if (originError) return originError;
  if (pathname === `${basePath}/sample`) {
    return htmlResponse(renderScripts(FEED_ORDER, { tenantId: 123, startDate: '2026-01-01', endDate: '2026-10-31' }, true));
  }
  try {
    const form = await request.formData();
    const session = await readSession(env, request);
    if (pathname === `${basePath}/generate`) {
      const { opts, kinds } = readForm(form, session?.tenantId ?? 0);
      return htmlResponse(renderScripts(kinds, opts, false));
    }
    if (pathname === `${basePath}/download`) {
      const { opts, kinds } = readForm(form, session?.tenantId ?? 0);
      const kind = kinds[0] ?? 'postings';
      return new Response(buildPowerQuery(kind, opts), {
        status: 200,
        headers: {
          'content-type': 'text/plain; charset=utf-8',
          'content-disposition': `attachment; filename="${FEEDS[kind].queryName}.pq"`,
          'cache-control': 'no-store',
          'x-content-type-options': 'nosniff',
        },
      });
    }
    if (pathname === `${basePath}/preview`) {
      if (!session || session.tenantId <= 0) throw new HttpError(401, 'Connect to ReAI and choose a company above first.');
      const { opts } = readForm(form, session.tenantId);
      const auth = { token: session.accessToken, tenantId: opts.tenantId };
      const [balances, pnl, invoices] = await Promise.all([
        /** @type {Promise<{ accounts: Array<{ accountNumber: string, closingBalance: number }> }>} */ (reaiRequest(env, '/api/ledger/general', { ...auth, query: { startDate: opts.endDate, endDate: opts.endDate, accountFrom: '1000', accountTo: '2999' } })),
        /** @type {Promise<{ accounts: Array<{ postings: Array<{ amount: number }> }> }>} */ (reaiRequest(env, '/api/ledger/general', { ...auth, query: { startDate: opts.startDate, endDate: opts.endDate, accountFrom: '3000', accountTo: '8999' } })),
        /** @type {Promise<{ totalItems: number }>} */ (reaiRequest(env, '/api/invoices', { ...auth, query: { startDate: opts.startDate, endDate: opts.endDate, page: '1', pageSize: '1' } })),
      ]);
      const postingCount = pnl.accounts.reduce((s, a) => s + a.postings.length, 0);
      const result = -pnl.accounts.reduce((s, a) => s + a.postings.reduce((t, p) => t + p.amount, 0), 0);
      const fmt = new Intl.NumberFormat('nb-NO', { minimumFractionDigits: 2, maximumFractionDigits: 2 });
      return htmlResponse(reaiCard({
        eyebrow: 'REAI DATA PREVIEW',
        title: `Tenant ${opts.tenantId} · ${opts.startDate} to ${opts.endDate}`,
        badge: reaiBadge({ text: 'Read only', tone: 'success' }),
        body: html`<div class="metric-grid">
          ${reaiMetric({ label: 'Result accounts', value: String(pnl.accounts.length), detail: `${postingCount} postings in period` })}
          ${reaiMetric({ label: 'Period result', value: fmt.format(result), detail: 'Income positive, before closing entries' })}
          ${reaiMetric({ label: 'Balance accounts', value: String(balances.accounts.length), detail: `Closing balances on ${opts.endDate}` })}
          ${reaiMetric({ label: 'Invoices', value: String(invoices.totalItems), detail: 'Issued in period' })}
        </div>`,
      }));
    }
  } catch (err) {
    return htmlResponse(reaiCallout({ tone: 'danger', title: `${BRAND} feed error`, body: err instanceof Error ? err.message : 'Failed.' }));
  }
  return errorResponse('Unknown route.', 404);
}
